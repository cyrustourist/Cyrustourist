/// نتیجهٔ تشخیص آفلاین آدرس از روی مختصات.
class OfflineAddress {
  const OfflineAddress({required this.state, required this.city, required this.text});

  /// نام فارسی استان (مطابق فهرست استان‌های فرم ثبت‌نام) یا خالی
  final String state;

  /// نام شهر نزدیک (اگر در شعاع مشخص شهر شناخته‌شده‌ای باشد) یا خالی
  final String city;

  /// متن آدرس آماده برای فیلد آدرس
  final String text;
}

class _Anchor {
  const _Anchor(this.city, this.province, this.lat, this.lng);
  final String city;
  final String province;
  final double lat;
  final double lng;
}

