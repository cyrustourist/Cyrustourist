  static String t(String key, [Map<String, String>? params]) {
    final table = fa ? _fa : (MenuLanguage.current == 'ar' ? _ar : _en);
    var s = table[key] ?? _en[key] ?? key;
    if (params != null) {
      params.forEach((k, v) => s = s.replaceAll('{$k}', v));
    }
    return s;
  }

