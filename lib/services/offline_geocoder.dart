  static const double _mPerDeg = 111320.0;

  static double _dist(double lat1, double lng1, double lat2, double lng2) {
    final dy = (lat1 - lat2) * _mPerDeg;
    final dx = (lng1 - lng2) * _mPerDeg * math.cos(lat1 * math.pi / 180);
    return math.sqrt(dx * dx + dy * dy);
  }

  /// آدرس تقریبی از روی مختصات، کاملاً آفلاین. اگر مختصات خارج از ایران باشد null می‌دهد.
  static Future<OfflineAddress?> reverse(LatLng p) async {
    if (p.latitude < 24.0 || p.latitude > 40.5 || p.longitude < 43.5 || p.longitude > 63.8) {
      return null;
    }
    _Anchor? best;
    var bestD = double.infinity;
    for (final a in _anchors) {
      final d = _dist(p.latitude, p.longitude, a.lat, a.lng);
      if (d < bestD) {
        bestD = d;
        best = a;
      }
    }
    if (best == null) return null;

    final city = bestD <= _cityRadius ? best.city : '';
    String? near;
    try {
      near = await LocalPoiService.instance.nearestName(p, maxMeters: _poiRadius);
    } catch (_) {}

    final parts = <String>[
      best.province,
      if (city.isNotEmpty) city,
      if (near != null && near.isNotEmpty) 'نزدیک $near',
    ];
    return OfflineAddress(state: best.province, city: city, text: parts.join('، '));
  }
